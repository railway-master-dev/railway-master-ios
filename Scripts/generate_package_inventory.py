#!/usr/bin/env python3
"""Generate or verify the reproducible source-file manifest for this package."""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "PACKAGE_INVENTORY.md"
EXCLUDED_DIRS = {".git", ".build", "DerivedData", "__pycache__", "xcuserdata"}
EXCLUDED_NAMES = {".DS_Store", OUTPUT.name}


def files_to_manifest() -> list[Path]:
    paths: list[Path] = []
    for path in ROOT.rglob("*"):
        if not path.is_file():
            continue
        relative = path.relative_to(ROOT)
        if any(part in EXCLUDED_DIRS for part in relative.parts):
            continue
        # Repository automation (CI workflows) is not package content and
        # legitimately differs between checkouts; keep it out of the
        # manifest so the check is identical in every environment.
        if relative.parts and relative.parts[0] == ".github":
            continue
        if path.name in EXCLUDED_NAMES or path.suffix == ".zip":
            continue
        paths.append(path)
    return sorted(paths, key=lambda path: path.relative_to(ROOT).as_posix())


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def render() -> str:
    paths = files_to_manifest()
    total_bytes = sum(path.stat().st_size for path in paths)
    swift_count = sum(path.suffix == ".swift" for path in paths)
    package_count = sum(path.name == "Package.swift" for path in paths)
    app_sources = sum(path.parent == ROOT / "RailwayMasterPhase1" and path.suffix == ".swift" for path in paths)
    test_sources = sum(path.parent == ROOT / "RailwayMasterPhase1Tests" and path.suffix == ".swift" for path in paths)
    bve_root = ROOT / "Research" / "BVE"
    bve_files = [path for path in paths if bve_root in path.parents]

    lines = [
        "# ZIP / Project File Inventory",
        "",
        f"This manifest is generated by `python3 Scripts/generate_package_inventory.py`. It is included in the ZIP. To avoid a self-referential hash, this file itself is excluded from the per-file rows below; every other project file is listed with its exact byte size and SHA-256. The ZIP archive has a single top-level directory containing the project.",
        "",
        "## Package summary",
        "",
        f"- Manifested project files (excluding this manifest): **{len(paths)}**",
        f"- Uncompressed bytes across manifested files: **{total_bytes}**",
        f"- Swift source files: **{swift_count}**",
        f"- Local Swift packages: **{package_count}**",
        f"- App Swift sources: **{app_sources}**",
        f"- App integration-test Swift sources: **{test_sources}**",
        f"- Bundled BVE research metadata files: **{len(bve_files)}** (metadata only; no source archives or third-party assets)",
        "- Final formal BVE metadata inventory: **69 route packages / 68 vehicle packages**; no duplicate archive SHA-256 values within either category; original BVE archives/assets are not bundled.",
        "",
        "## Files",
        "",
        "| Project-relative path | Bytes | SHA-256 |",
        "|---|---:|---|",
    ]
    for path in paths:
        relative = path.relative_to(ROOT).as_posix().replace("|", "%7C")
        lines.append(f"| `{relative}` | {path.stat().st_size} | `{sha256(path)}` |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the inventory is missing or stale")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != expected:
            print("FAIL: PACKAGE_INVENTORY.md is missing or stale; run python3 Scripts/generate_package_inventory.py", file=sys.stderr)
            return 1
        print("PASS: PACKAGE_INVENTORY.md matches all manifested files and SHA-256 values")
        return 0
    OUTPUT.write_text(expected, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} with {len(files_to_manifest())} file rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
